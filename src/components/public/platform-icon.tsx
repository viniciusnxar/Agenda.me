import { Globe, Link, Mail, Music2, type LucideProps } from "lucide-react";

import type { Platform } from "@/lib/social";

// O lucide 1.x não traz mais ícones de marcas; estes seguem o mesmo traço (24x24, stroke 2).
function BrandIcon({ children, ...props }: React.SVGProps<SVGSVGElement>) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

const brandPaths: Partial<Record<Platform, React.ReactNode>> = {
  instagram: (
    <>
      <rect width="20" height="20" x="2" y="2" rx="5" ry="5" />
      <path d="M16 11.37A4 4 0 1 1 12.63 8 4 4 0 0 1 16 11.37z" />
      <line x1="17.5" x2="17.51" y1="6.5" y2="6.5" />
    </>
  ),
  facebook: <path d="M18 2h-3a5 5 0 0 0-5 5v3H7v4h3v8h4v-8h3l1-4h-4V7a1 1 0 0 1 1-1h3z" />,
  youtube: (
    <>
      <path d="M2.5 17a24.12 24.12 0 0 1 0-10 2 2 0 0 1 1.4-1.4 49.56 49.56 0 0 1 16.2 0A2 2 0 0 1 21.5 7a24.12 24.12 0 0 1 0 10 2 2 0 0 1-1.4 1.4 49.55 49.55 0 0 1-16.2 0A2 2 0 0 1 2.5 17" />
      <path d="m10 15 5-3-5-3z" />
    </>
  ),
  linkedin: (
    <>
      <path d="M16 8a6 6 0 0 1 6 6v7h-4v-7a2 2 0 0 0-2-2 2 2 0 0 0-2 2v7h-4v-7a6 6 0 0 1 6-6z" />
      <rect width="4" height="12" x="2" y="9" />
      <circle cx="4" cy="4" r="2" />
    </>
  ),
};

const lucideIcons: Partial<Record<Platform, React.ComponentType<LucideProps>>> = {
  tiktok: Music2,
  site: Globe,
  email: Mail,
  outro: Link,
};

export function PlatformIcon({ platform, className }: { platform: Platform; className?: string }) {
  const brand = brandPaths[platform];
  if (brand) return <BrandIcon className={className}>{brand}</BrandIcon>;
  const Icon = lucideIcons[platform] ?? Link;
  return <Icon className={className} aria-hidden="true" />;
}
